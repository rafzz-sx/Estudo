-- 1. Impedir que o problema volte
-- ════════════════════════════════════════════════════════════════════
-- Sem esta UNIQUE, duas linhas com o mesmo nome na mesma matéria eram
-- possíveis, e o ON CONFLICT dos seeds não tinha em que se apoiar.

-- Funde duplicatas exatas que já existam, antes de criar a restrição.
-- As SETE tabelas são remapeadas: o DELETE logo abaixo é CASCADE na
-- maioria delas, então apontar só `questoes` para o sobrevivente
-- apagaria em silêncio o bizu e a vídeo-aula presos na duplicata.
CREATE TEMP TABLE fusao_duplicata AS
SELECT id AS id_velho,
       FIRST_VALUE(id) OVER (PARTITION BY materia_id, nome ORDER BY id) AS id_novo
FROM assuntos;

DELETE FROM fusao_duplicata WHERE id_velho = id_novo;
CREATE INDEX ON fusao_duplicata(id_velho);

UPDATE questoes t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;
UPDATE bizus t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;
UPDATE concurso_assuntos t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;
UPDATE user_progresso t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;
UPDATE videoaulas t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;
UPDATE teoria_conteudo t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;
UPDATE plano_itens t SET assunto_id = f.id_novo
FROM fusao_duplicata f WHERE t.assunto_id = f.id_velho;

DELETE FROM assuntos a
USING fusao_duplicata f WHERE f.id_velho = a.id;

DROP TABLE fusao_duplicata;

